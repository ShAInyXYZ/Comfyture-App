const NS = "http://www.w3.org/2000/svg";

/** Renders text into el as dots; height follows the element's CSS height. */
export function matrix(el, text) {
  const chars = [...String(text).toUpperCase()];
  if (el.dataset.text === chars.join("")) return;
  el.dataset.text = chars.join("");
  const cols = chars.length * 6 - 1;
  const svg = document.createElementNS(NS, "svg");
  svg.setAttribute("viewBox", `0 0 ${cols * 2} 14`);
  svg.setAttribute("aria-hidden", "true");
  chars.forEach((ch, i) => {
    const bits = GLYPHS[ch] ?? GLYPHS[" "];
    for (let n = 0; n < 35; n++) {
      const dot = document.createElementNS(NS, "circle");
      dot.setAttribute("cx", String((i * 6 + (n % 5)) * 2 + 1));
      dot.setAttribute("cy", String(Math.floor(n / 5) * 2 + 1));
      dot.setAttribute("r", ".78");
      if (bits[n] === "1") dot.setAttribute("class", "on");
      svg.append(dot);
    }
  });
  el.replaceChildren(svg);
  el.setAttribute("aria-label", String(text));
}
